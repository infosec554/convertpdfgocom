// T - tarjimani olish
func T(lang, key string) string {
	if translations, ok := Translations[lang]; ok {
		if text, ok := translations[key]; ok {
			return text
		}
	}
	// Default: English yoki O'zbekcha
	if text, ok := Translations["en"][key]; ok {
		return text
	}
	if text, ok := Translations["uz"][key]; ok {
		return text
	}
	return key
}

// GetKey - matn bo'yicha kalitni topish (Reply Keyboard uchun)
func GetKey(lang, text string) string {
	if translations, ok := Translations[lang]; ok {
		for key, val := range translations {
			if val == text {
				return key
			}
		}
	}
	return ""
}
